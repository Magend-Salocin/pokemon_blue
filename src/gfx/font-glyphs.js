/** Overlays the non-transparent pixels of `overlay` on `base`, starting at row 0. */
export function overlayRows(base, overlay) {
  return base.map((row, y) => {
    const top = overlay[y];
    if (!top) return row;
    return [...row].map((pixel, x) => (top[x] !== '.' ? top[x] : pixel)).join('');
  });
}

/** Map of character → 8 rows, including composed accented letters. */
export function buildGlyphTable() {
  const table = new Map(Object.entries(BASE_GLYPHS));
  for (const [character, [base, accent]] of Object.entries(COMPOSITES)) {
    const baseRows = typeof base === 'string' ? BASE_GLYPHS[base] : base;
    table.set(character, overlayRows(baseRows, accent));
  }
  return table;
}
