function counter(left, right) {
  let rows = [
    '3333333333333333',
    '0000000000000000',
    '0000000000000000',
    '1111111111111111',
    '3333333333333333',
    '2222222222222222',
    '2111211121112111',
    '2111211121112111',
    '2111211121112111',
    '2111211121112111',
    '2222222222222222',
    '3333333333333333',
  ];
  if (left) rows = rows.map((row) => `3${row.slice(1)}`);
  if (right) rows = rows.map((row) => `${row.slice(0, 15)}3`);
  return overlay(FLOOR_TILE, rows, 0, 2);
}

